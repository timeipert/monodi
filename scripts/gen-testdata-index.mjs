// Writes src/app/testdata/index.ts importing every fixture JSON (used by Karma specs).
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const base = join(dirname(fileURLToPath(import.meta.url)), '../src/app/testdata');
const groups = [['', 'real'], ['extreme/', 'extreme']];
const lines = ['// GENERATED by scripts/gen-testdata-index.mjs - do not edit.', ''];
const entries = [];
let i = 0;
for (const [dir, kind] of groups) {
  if (!existsSync(join(base, dir))) continue;
  for (const f of readdirSync(join(base, dir)).filter((x) => x.endsWith('.json') && x !== 'manifest.json').sort()) {
    const v = `f${i++}`;
    lines.push(`import ${v} from './${dir}${f}';`);
    entries.push(`  { name: ${JSON.stringify(f.replace(/\.json$/, ''))}, kind: '${kind}' as const, doc: ${v} as any },`);
  }
}
lines.push('', 'export const FIXTURES: { name: string; kind: \'real\' | \'extreme\'; doc: any }[] = [', ...entries, '];', '');
writeFileSync(join(base, 'index.ts'), lines.join('\n'));
console.log('wrote testdata/index.ts with', entries.length, 'fixtures');
